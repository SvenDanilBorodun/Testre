"""Generate TRAINING_HANDLER_SHA256, the sha256 of training_handler.py (spec §3.10, V2-1). Stdlib only.

    python robotis_ai_setup/modal_training/make_handler_hash.py            # regenerate
    python robotis_ai_setup/modal_training/make_handler_hash.py --check    # hash file == handler

The sibling of make_training_lock.py. The worker hashes the handler file it runs
(training_handler.py::_handler_sha256: the trainer image's /app/training_handler.py,
Modal's /root/training_handler.py, both the repo file's bytes) and sends it in
POST .../start beside the lock hash; the API compares it with the constant written
here and refuses any other value as wrong_image, so a forgotten manual Modal deploy
or an older trainer image never trains.

Every edit to training_handler.py is therefore followed by this script in the same
commit (tests/test_training_handler_hash.py fails until then), and it ships only with
a new trainer image AND a Modal deploy.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
HANDLER_PATH = HERE / "training_handler.py"
HASH_PATH = HERE.parent / "cloud_training_api" / "app" / "services" / "training_handler_hash.py"


def render_hash_module(handler_bytes: bytes) -> str:
    digest = hashlib.sha256(handler_bytes).hexdigest()
    return (
        '"""Generated by robotis_ai_setup/modal_training/make_handler_hash.py; do not edit.\n\n'
        "sha256 of modal_training/training_handler.py. The worker sends the hash of the handler\n"
        "file it runs in POST .../start; any other value is refused as wrong_image.\n"
        '"""\n\n'
        f'TRAINING_HANDLER_SHA256 = "{digest}"\n'
    )


def check(handler_path: Path = HANDLER_PATH, hash_path: Path = HASH_PATH) -> int:
    handler = handler_path.read_bytes()
    want = render_hash_module(handler)
    have = hash_path.read_text(encoding="utf-8") if hash_path.is_file() else ""
    digest = hashlib.sha256(handler).hexdigest()
    if have != want:
        print(f"MISMATCH: {hash_path} does not carry sha256({handler_path.name}) = {digest}; "
              f"run {Path(__file__).name}", file=sys.stderr)
        return 1
    print(f"OK: TRAINING_HANDLER_SHA256 = {digest}")
    return 0


def generate(handler_path: Path = HANDLER_PATH, hash_path: Path = HASH_PATH) -> int:
    hash_path.write_text(render_hash_module(handler_path.read_bytes()), encoding="utf-8", newline="\n")
    print(f"wrote {hash_path}")
    return check(handler_path, hash_path)


def main(argv: list[str]) -> int:
    if argv == ["--check"]:
        return check()
    if argv:
        print(__doc__, file=sys.stderr)
        return 2
    return generate()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
