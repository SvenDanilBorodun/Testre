"""Modal app for EduBotics cloud GPU training.

Deploy (from robotis_ai_setup/modal_training):
    modal deploy modal_app.py                                       # prod: edubotics-training
    EDUBOTICS_TRAINING_VARIANT=dev modal deploy modal_app.py        # dev:  edubotics-training-dev
Smoke:
    modal run -m modal_app::smoke_test

Two variants (spec §3.8), baked into the image env so the container's re-import
agrees with the deploy:

  prod  app `edubotics-training`: `train` + `train_vla` (legacy, secret
        `edubotics-training-secrets`), `train_managed` (no secret), `smoke_test`.
  dev   app `edubotics-training-dev`: `train_managed` + `smoke_test` only, and no
        secret is referenced anywhere (the E2E stack, E5).

The Railway API dispatches legacy jobs with `modal.Function.from_name(<app>,
"train" | "train_vla").spawn(...)` and managed ACT attempts with
`train_managed.spawn(training_id=, attempt=, worker_token=, api_url=,
supabase_url=, supabase_anon_key=)`; `train_managed` gets everything it needs as
arguments and talks only to the API's worker endpoints and the scoped RPC.

The image installs the ONE training lock (training-lock.txt, generated by
make_training_lock.py) with --no-deps, exactly like the RunPod trainer image
(CLAUDE.md Rule §5, R2), and checks it with check_training_lock.py.
"""

import os
from pathlib import Path

import modal

VARIANTS = {
    "prod": {"app": "edubotics-training", "legacy": True},
    "dev": {"app": "edubotics-training-dev", "legacy": False},
}
VARIANT = os.environ.get("EDUBOTICS_TRAINING_VARIANT", "prod")
if VARIANT not in VARIANTS:
    raise RuntimeError(f"EDUBOTICS_TRAINING_VARIANT must be one of {sorted(VARIANTS)}")
CFG = VARIANTS[VARIANT]

HERE = Path(__file__).resolve().parent
LOCK_IN_IMAGE = "/root/training-lock.txt"
CHECK_IN_IMAGE = "/root/check_training_lock.py"
# The one install command (make_training_lock.INSTALL_COMMAND), with the lock's image path.
INSTALL_LOCK = (
    "python -m pip install --no-cache-dir --no-deps -r /root/training-lock.txt "
    "--index-url https://pypi.org/simple --extra-index-url https://download.pytorch.org/whl/cu126"
)

app = modal.App(CFG["app"])

image = (
    modal.Image.from_registry(
        # CUDA 12.6.1 matches the lock's torch 2.7.0+cu126 (LeRobot 0.5.1 allows
        # torch>=2.7,<2.11). Modal L4 GPUs run R550+ drivers; CUDA 12.6 is supported.
        "nvidia/cuda:12.6.1-devel-ubuntu22.04",
        add_python="3.12",
    )
    # clang + build-essential: the lock's evdev is an sdist with a C extension.
    .apt_install("git", "ffmpeg", "clang", "build-essential")
    .add_local_file(HERE / "training-lock.txt", LOCK_IN_IMAGE, copy=True)
    .add_local_file(HERE / "check_training_lock.py", CHECK_IN_IMAGE, copy=True)
    .run_commands(INSTALL_LOCK, f"python {CHECK_IN_IMAGE}")
    .env({"PYTHONUNBUFFERED": "1", "EDUBOTICS_TRAINING_VARIANT": VARIANT})
    .add_local_python_source("training_handler")
)

legacy_secrets = (
    [modal.Secret.from_name("edubotics-training-secrets")] if CFG["legacy"] else []
)


@app.function(image=image, gpu="L4", cpu=8, timeout=7 * 3600, min_containers=0)  # FR-9: the budget, not Modal, ends an attempt
def train_managed(training_id: int, attempt: int, worker_token: str, api_url: str,
                  supabase_url: str, supabase_anon_key: str) -> dict:
    """One managed ACT attempt (spec §4.7). No secret: all credentials are per-attempt arguments."""
    from training_handler import run_managed
    return run_managed(api_url, supabase_url, supabase_anon_key, training_id, attempt,
                       worker_token, cpu_budget=8)


if CFG["legacy"]:

    @app.function(
        image=image,
        gpu="L4",
        timeout=7 * 3600,
        secrets=legacy_secrets,
        min_containers=0,
    )
    def train(
        dataset_name: str,
        model_name: str,
        model_type: str,
        training_params: dict,
        training_id: int,
        worker_token: str,
    ) -> dict:
        """Single legacy training job. Returns {"status": "succeeded"|"failed", ...}."""
        from training_handler import run_training

        return run_training(
            dataset_name=dataset_name,
            model_name=model_name,
            model_type=model_type,
            training_params=training_params,
            training_id=training_id,
            worker_token=worker_token,
        )

    @app.function(
        image=image,
        # VLA policies (pi0 / pi05 / pi0_fast / smolvla) are 0.45-3.6 B-param
        # vision-language-action models. pi0/pi05/pi0_fast (~3 B, PaliGemma) OOM
        # on the 24 GB L4 even in bf16; they need an 80 GB A100. ACT-class policies
        # stay on the cheaper L4 `train` above. Same body — only the GPU and
        # timeout differ. timeout=11h covers the 10h A100-tier policy cap
        # (routes/training.py POLICY_MAX_TIMEOUT_HOURS) so the cap is actually
        # reachable (the L4 `train` keeps its 7h bound, above its ≤6h L4-tier caps).
        gpu="A100-80GB",
        timeout=11 * 3600,
        secrets=legacy_secrets,
        min_containers=0,
    )
    def train_vla(
        dataset_name: str,
        model_name: str,
        model_type: str,
        training_params: dict,
        training_id: int,
        worker_token: str,
    ) -> dict:
        """VLA training job (pi0/pi05/pi0_fast/smolvla) on an A100-80GB.

        Identical body to `train`; the Cloud API routes A100-tier policies here via
        the per-policy GPU tier in app.services.policy_profile. Returns
        {"status": "succeeded"|"failed"|"canceled", ...}."""
        from training_handler import run_training

        return run_training(
            dataset_name=dataset_name,
            model_name=model_name,
            model_type=model_type,
            training_params=training_params,
            training_id=training_id,
            worker_token=worker_token,
        )


@app.function(image=image, secrets=legacy_secrets)
def smoke_test():
    """Verify the image boots, matches the lock, and imports what training needs.

    The prod deploy moves train/train_vla onto the lock-based image too, and
    nothing in the E2E plan trains a VLA, so the VLA modules are imported here
    (FR-20). Usage: modal run -m modal_app::smoke_test
    """
    import os
    import subprocess
    import sys

    lock = subprocess.run([sys.executable, CHECK_IN_IMAGE], capture_output=True, text=True)
    print(lock.stdout + lock.stderr)

    import torch
    import transformers  # noqa: F401
    import lerobot.policies.act.modeling_act  # noqa: F401
    import lerobot.policies.pi0.modeling_pi0  # noqa: F401
    import lerobot.policies.smolvla.modeling_smolvla  # noqa: F401

    required = ("SUPABASE_URL", "SUPABASE_ANON_KEY", "HF_TOKEN") if CFG["legacy"] else ()
    missing = [k for k in required if not os.environ.get(k)]
    print(f"variant={VARIANT} torch={torch.__version__} cuda_available={torch.cuda.is_available()}")
    print(f"missing secrets: {missing or 'none'}")
    # Plain Python types only: torch.__version__ is a TorchVersion subclass, and
    # unpickling it on a torch-less Mac raises DeserializationError in `modal run`.
    return {
        "variant": VARIANT,
        "lock_ok": lock.returncode == 0,
        "torch": str(torch.__version__),
        "cuda_available": bool(torch.cuda.is_available()),
        "missing_secrets": list(missing),
    }
