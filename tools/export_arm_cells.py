def read_stl(path: Path) -> np.ndarray:
    data = path.read_bytes()
    n = struct.unpack('<I', data[80:84])[0]
    if 84 + 50 * n != len(data):
        raise ValueError(f'not a binary STL: {path}')
    rec = np.dtype([('n', '<f4', 3), ('v', '<f4', (3, 3)), ('a', '<u2')])
    return np.frombuffer(data, dtype=rec, count=n, offset=84)['v'].astype(np.float64)


def _floats(text, default):
    return [float(v) for v in (text if text else default).split()]


def rpy_matrix(r, p, y):
    cr, sr, cp, sp, cy, sy = math.cos(r), math.sin(r), math.cos(p), math.sin(p), math.cos(y), math.sin(y)
    return np.array([[cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr],
                     [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr],
                     [-sp, cp * sr, cp * cr]])


def _transform(origin):
    t = np.eye(4)
    if origin is not None:
        t[:3, :3] = rpy_matrix(*_floats(origin.get('rpy'), '0 0 0'))
        t[:3, 3] = _floats(origin.get('xyz'), '0 0 0')
    return t


class Urdf:
    def __init__(self, path: Path):
        self.dir = path.parent
        root = ET.parse(path).getroot()
        self.joints = {}
        for j in root.findall('joint'):
            axis = j.find('axis')
            mimic = j.find('mimic')
            self.joints[j.get('name')] = dict(
                parent=j.find('parent').get('link'), child=j.find('child').get('link'),
                origin=_transform(j.find('origin')),
                axis=_floats(axis.get('xyz'), '0 0 1') if axis is not None else None,
                multiplier=float(mimic.get('multiplier') or 1.0) if mimic is not None else 1.0)
        self.visuals = {}
        for link in root.findall('link'):
            out = []
            for v in link.findall('visual'):
                mesh = v.find('geometry/mesh')
                if mesh is None:
                    continue
                out.append((mesh.get('filename').replace('package://', ''), _transform(v.find('origin')),
                            np.array(_floats(mesh.get('scale'), '1 1 1'))))
            self.visuals[link.get('name')] = out

    def mesh_paths(self, link):
        return [(self.dir / fn).resolve() for fn, _t, _s in self.visuals[link]]

    def tris(self, link):
        """triangles (n, 3, 3) of a link in its own frame."""
        out = []
        for fn, t, scale in self.visuals[link]:
            v = (read_stl(self.dir / fn) * scale).reshape(-1, 3)
            out.append((v @ t[:3, :3].T + t[:3, 3]).reshape(-1, 3, 3))
        return np.concatenate(out)

    def fixed_between(self, parent, child):
        """the fixed transform parent -> child for a child on fixed joints below parent."""
        chain = []
        link = child
        while link != parent:
            name, joint = next((n, j) for n, j in self.joints.items() if j['child'] == link)
            chain.append(joint['origin'])
            link = joint['parent']
        t = np.eye(4)
        for m in reversed(chain):
            t = t @ m
        return t


def aabb(points, pad):
    return points.min(0) - pad, points.max(0) + pad


def cells_of(tris, pad):
    """the non-empty cells of a GRID^3 grid of the triangles' AABB; each cell the AABB of the
    triangles whose centroid falls in it, padded."""
    pts = tris.reshape(-1, 3)
    lo, hi = pts.min(0), pts.max(0)
    idx = np.clip(((tris.mean(1) - lo) / np.maximum(hi - lo, 1e-12) * GRID).astype(int), 0, GRID - 1)
    key = idx[:, 0] * GRID * GRID + idx[:, 1] * GRID + idx[:, 2]
    return [aabb(tris[key == k].reshape(-1, 3), pad) for k in np.unique(key)]


def _vec(v):
    return '(' + ', '.join(repr(float(x)) for x in v) + ')'


def _box(lo, hi):
    return f'({_vec(lo)}, {_vec(hi)})'


def _cells(cells, indent):
    pad = ' ' * indent
    return '(\n' + ''.join(f'{pad}    {_box(lo, hi)},\n' for lo, hi in cells) + f'{pad})'


def build():
    """-> (module text, {input path: sha256})"""
    lines, inputs = [HEADER, 'ARM_CELLS = {\n'], {}
    for key in ('omx', 'v1'):
        spec = ARMS[key]
        urdf = Urdf(spec['urdf'])
        inputs[spec['urdf']] = None
        pad = spec['pad']
        lines.append(f"    '{key}': {{\n        'pad_m': {pad!r},\n")
        if spec['links']:
            boxes = []
            for link in spec['links']:
                inputs.update((p, None) for p in urdf.mesh_paths(link))
                boxes.append(aabb(urdf.tris(link).reshape(-1, 3), pad))
            lines.append("        'link_boxes': (\n" + ''.join(f'            {_box(*b)},\n' for b in boxes)
                         + '        ),\n')
        else:
            lines.append("        'link_boxes': None,\n")
        hous = []
        for link in spec['housing']:
            inputs.update((p, None) for p in urdf.mesh_paths(link))
            t = urdf.fixed_between('link5', link)
            v = urdf.tris(link).reshape(-1, 3)
            hous.append((v @ t[:3, :3].T + t[:3, 3]).reshape(-1, 3, 3))
        hous = np.concatenate(hous)
        lines.append("        'housing': {\n"
                     f"            'box': {_box(*aabb(hous.reshape(-1, 3), pad))},\n"
                     f"            'cells': {_cells(cells_of(hous, pad), 12)},\n"
                     '        },\n')
        lines.append("        'blades': (\n")
        for link, joint_name in spec['blades']:
            inputs.update((p, None) for p in urdf.mesh_paths(link))
            joint = urdf.joints[joint_name]
            origin = urdf.fixed_between('link5', joint['parent']) @ joint['origin']
            tris = urdf.tris(link)
            r_max = float(np.linalg.norm(tris.reshape(-1, 3), axis=1).max())
            mult = joint['multiplier']
            slack = (1.0 - abs(mult)) if (key == 'v1' and mult != 1.0) else 0.0
            rows = ', '.join(_vec(origin[r]) for r in range(3))
            lines.append('            {\n'
                         f"                'name': {link!r}, 'joint': {joint_name!r},\n"
                         f"                'origin': ({rows}),\n"
                         f"                'axis': {_vec(joint['axis'])}, 'multiplier': {mult!r}, "
                         f"'gear_slack': {slack!r},\n"
                         f"                'r_max_m': {r_max!r},\n"
                         f"                'box': {_box(*aabb(tris.reshape(-1, 3), pad))},\n"
                         f"                'cells': {_cells(cells_of(tris, pad), 16)},\n"
                         '            },\n')
        lines.append('        ),\n    },\n')
    lines.append('}\n')
    text = ''.join(lines)
    digests = {p: hashlib.sha256(p.read_bytes()).hexdigest() for p in inputs}
    return text, digests


def render_fixture(text, digests):
    rows = {Path(p).relative_to(REPO).as_posix(): d for p, d in digests.items()}
    rows[OUT.relative_to(REPO).as_posix()] = hashlib.sha256(text.encode('utf-8')).hexdigest()
    return ''.join(f'{d}  {p}\n' for p, d in sorted(rows.items()))


def main(argv) -> int:
    text, digests = build()
    fixture = render_fixture(text, digests)
    if '--check' in argv:
        stale = [p for p, want in ((OUT, text), (SHA_FIXTURE, fixture))
                 if not p.exists() or p.read_text(encoding='utf-8') != want]
        for p in stale:
            print(f'stale: {p.relative_to(REPO)}', file=sys.stderr)
        return 1 if stale else 0
    OUT.write_text(text, encoding='utf-8')
    SHA_FIXTURE.write_text(fixture, encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
