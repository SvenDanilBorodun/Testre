"""GENERATED by tools/export_arm_cells.py — never edit by hand.

The tower guard's arm boxes (spec 40 S6.2 revision 4), from the meshes the web
app ships; ``fixture_guard`` reads them. Per arm: ``link_boxes`` (links 1–4,
``(lo, hi)`` in each link's own frame; ``None`` on the V1, whose links 1–4 are
``arm_geometry.V1_LINK_BOXES``), the ``housing`` fixed to link 5 and the
``blades``, each in its OWN frame, placed by ``origin`` (link 5 -> the blade's
joint frame, rows), a turn about ``axis`` by ``multiplier`` × the claw value.
Level 1 is ``box``; level 2 ``cells`` (each inside its box). ``r_max_m`` is a
blade's largest vertex distance from its pivot; ``gear_slack`` the V1 mimic
blade's ratio difference (1 against the URDF's 18/19).
``test/fixtures/arm_cells.sha256`` pins the inputs and this file.
"""

